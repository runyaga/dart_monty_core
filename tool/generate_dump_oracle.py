#!/usr/bin/env python3
"""Record an idle dump made by upstream's pydantic-monty 1.1.0 into test/unit/worker/_dump_oracle.g.dart.

usage: PYTHON -I tool/generate_dump_oracle.py [--check]

PYTHON is an interpreter with the pydantic-monty that tool/upstream/requirements.lock pins installed (the oracle).
The two directions of dump portability, each a same-version idle dump:

- upstream to core: the dump recorded here (`upstreamIdleDumpHex`) is loaded by
  core in test/unit/worker/_boundary_cases.dart and must continue as `expected`;
- core to upstream: `test/unit/worker/_core_dump_fixture.g.dart` holds a dump made
  by core's worker (tool/record_core_dump_fixture.dart rewrites it, noting the worker sources it
  was made from); --check loads it in upstream, requires the same continuation,
  and fails when the worker sources have changed since it was recorded.

Dumps are not byte-reproducible (two dumps of one state differ), so --check
does not compare bytes: it loads both dumps in upstream and checks the
continuation, and checks that the rest of the generated file is unchanged.

--check writes nothing and exits 1 if either dump does not load and continue
as expected in the pinned upstream, or the generated file's other lines differ.
"""

from __future__ import annotations

import asyncio
import json
import re
import subprocess
import sys
from pathlib import Path

import pydantic_monty as pm

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'test/unit/worker/_dump_oracle.g.dart'
CORE = ROOT / 'test/unit/worker/_core_dump_fixture.g.dart'

STATE = 'x = [1, 2, 3]\ny = {"a": "b"}\ndef f(a):\n    return a + 1\n'
CONTINUATION = 'repr((x, y, f(1)))'
EXPECTED = "([1, 2, 3], {'a': 'b'}, 2)"

TEMPLATE = """\
// An idle dump made by upstream pydantic-monty 1.1.0 (the oracle), and what it
// must continue as, recorded by tool/generate_dump_oracle.py. Core loads it in
// _boundary_cases.dart. The bytes are one recording: dumps are not reproducible.
//
// Generated by tool/generate_dump_oracle.py; do not edit by hand.

/// The code fed before the dump.
const dumpStateCode = {state};

/// The code fed after loading the dump.
const dumpContinuationCode = {continuation};

/// What [dumpContinuationCode] returns after a load, as `repr` shows it.
const dumpContinuationExpected = {expected};

/// The dump, as hex.
const upstreamIdleDumpHex = '{hex}';
"""


def dart_str(s: str) -> str:
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"


def render(hex_dump: str) -> str:
    text = TEMPLATE.format(
        state=dart_str(STATE), continuation=dart_str(CONTINUATION), expected=dart_str(EXPECTED), hex=hex_dump
    )
    return subprocess.run(
        ['dart', 'format', '--stdin-name', str(OUT)], input=text, capture_output=True, text=True, check=True, cwd=ROOT
    ).stdout


async def make_dump(pool) -> bytes:
    async with pool.checkout() as session:
        await session.feed_run(STATE)
        return await session.dump()


async def continues(pool, dump: bytes) -> str:
    async with pool.checkout() as session:
        await session.load_session(dump)
        return str(await session.feed_run(CONTINUATION))


def committed_hex(path: Path, name: str, digits: str = '[0-9a-f]+') -> str:
    match = re.search(rf"{name}\s*=\s*'({digits})'", path.read_text())
    if not match:
        raise SystemExit(f'{path.relative_to(ROOT)}: no {name}')
    return match.group(1)


async def check() -> int:
    bad = 0
    upstream_hex = committed_hex(OUT, 'upstreamIdleDumpHex')
    if OUT.read_text() != render(upstream_hex):
        print(f'{OUT.relative_to(ROOT)} differs from its template', file=sys.stderr)
        bad = 1
    recorded = committed_hex(CORE, 'coreIdleDumpWorkerSources', digits='[0-9a-f]+')
    current = json.loads((ROOT / 'tool/wasm-provenance.json').read_text())['worker_source_sha256']
    if recorded != current:
        print(
            'the worker sources changed since the core dump fixture was recorded: '
            'run `dart run tool/record_core_dump_fixture.dart` and commit it',
            file=sys.stderr,
        )
        bad = 1
    async with pm.AsyncMonty(max_processes=1) as pool:
        for label, dump in (
            ('upstream dump', bytes.fromhex(upstream_hex)),
            ('core dump (tool/record_core_dump_fixture.dart)', bytes.fromhex(committed_hex(CORE, 'coreIdleDumpHex'))),
        ):
            try:
                got = await continues(pool, dump)
            except BaseException as e:  # noqa: BLE001 - any failure is the answer
                got = f'{type(e).__name__}: {e}'
            if got != EXPECTED:
                print(f'{label}: continued as {got!r}, expected {EXPECTED!r}', file=sys.stderr)
                bad = 1
    return bad


async def record() -> None:
    async with pm.AsyncMonty(max_processes=1) as pool:
        dump = await make_dump(pool)
        assert await continues(pool, dump) == EXPECTED
    OUT.write_text(render(dump.hex()))


def main() -> int:
    if '--check' in sys.argv[1:]:
        return asyncio.run(check())
    asyncio.run(record())
    return 0


if __name__ == '__main__':
    sys.exit(main())
