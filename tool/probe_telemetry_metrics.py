"""Capture 1.1.0 raw metrics for R-3; run with the oracle venv's Python.

Requires the optional opentelemetry-api extra. No Dart code is imported.
Writes a web-safe fixture to stdout; timings and transport sizes are masked.
"""
import json
from pathlib import Path

import pydantic_monty as pm
from opentelemetry.context import Context, attach, detach
from opentelemetry.trace import NonRecordingSpan, SpanContext, set_span_in_context


class Instrument:
    def __init__(self, meter, name, kind, unit, description):
        self.meter = meter
        self.metadata = dict(name=name, kind=kind, unit=unit, description=description)

    def record(self, value, attributes=None, context=None):
        assert context == Context(), "metric inherited ambient context"
        self.meter.records.append(dict(self.metadata, value=value,
                                       attributes=dict(attributes or {})))

    add = record


class Meter:
    def __init__(self):
        self.records = []

    def create_counter(self, name, unit='', description=''):
        return Instrument(self, name, 'counter', unit, description)

    def create_up_down_counter(self, name, unit='', description=''):
        return Instrument(self, name, 'up_down_counter', unit, description)

    def create_histogram(self, name, unit='', description='', **kwargs):
        return Instrument(self, name, 'histogram', unit, description)


def scenario(name, pool):
    with pool.checkout() as session:
        if name == 'plain':
            assert session.feed_run('1 + 1') == 2
        elif name == 'print':
            session.feed_run("print('é🙂')", print_callback=lambda *args: None)
        elif name == 'external':
            assert session.feed_run('ext(21)', external_lookup={'ext': lambda x: x * 2}) == 42
        elif name == 'manual':
            snapshot = session.feed_start('ext(21)')
            snapshot.trace_context()
            assert snapshot.resume({'return_value': 42}).output == 42
        elif name == 'error':
            try:
                session.feed_run('1/0')
            except pm.MontyRuntimeError:
                pass
            else:
                raise AssertionError('expected ZeroDivisionError')
        elif name == 'dump_load':
            session.feed_run('x = 42')
            state = session.dump()
            sizes = [r['value'] for r in meter.records if r['name'] == 'monty.snapshot.bytes']
            assert sizes == [len(state)]
            with pool.checkout() as restored:
                restored.load_session(state)
                assert restored.feed_run('x') == 42


PIN = json.loads(
    (Path(__file__).resolve().parent.parent / 'tool/upstream/upstream-pin.json').read_text(
        encoding='utf-8'
    )
)
assert pm.__version__ == PIN['version'], pm.__version__
meter = Meter()
pm.instrument_telemetry(meter=meter)
output = {}
host = NonRecordingSpan(SpanContext(trace_id=1, span_id=2, is_remote=False))
token = attach(set_span_in_context(host))
try:
    for name in ['plain', 'print', 'external', 'manual', 'error', 'dump_load']:
        meter.records.clear()
        with pm.Monty(min_processes=1, max_processes=2) as pool:
            scenario(name, pool)
        records = []
        for record in meter.records:
            normalized = dict(record)
            if record['unit'] == 's':
                normalized['value'] = '<seconds>'
            elif record['name'] in ['monty.wire.frame.bytes', 'monty.snapshot.bytes']:
                normalized['value'] = '<bytes>'
            records.append(normalized)
        output[name] = records
finally:
    detach(token)
print('// Generated by tool/probe_telemetry_metrics.py with pydantic-monty 1.1.0.')
print('// Raw measurements: timing masked; own-run snapshot length checked by probe.')
print("const metricOracleJson = '''\n" + json.dumps(output, indent=2) + "''';")
