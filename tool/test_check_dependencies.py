#!/usr/bin/env python3
"""Unit tests for tool/check_dependencies.py against temporary lockfiles.

The allowlist under test is the real one, tool/dependency_allowlist.txt;
only pubspec.lock is faked, in a temp directory, because the real lock is
generated by `dart pub get` in CI and is not committed.

Usage: python3 -I tool/test_check_dependencies.py
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECK = ROOT / 'tool' / 'check_dependencies.py'

# Names the seeded allowlist definitely contains (and forbidden/unknown ones
# it definitely does not).
ALLOWED = ('_fe_analyzer_shared', 'collection', 'monty_conformance', 'path',
           'test', 'web_socket_channel')


def lockfile(*names: str) -> str:
    """A pubspec.lock-shaped text resolving exactly `names`.

    Entry bodies use 4- and 6-space indentation so the tests also prove the
    parser only reads the 2-space-indented package keys, and the trailing
    `sdks:` block proves it stops at the end of `packages:`.
    """
    entries = []
    for name in names:
        entries.append(
            f'  {name}:\n'
            '    dependency: "direct main"\n'
            '    description:\n'
            f'      name: {name}\n'
            '      url: "https://pub.dev"\n'
            '    source: hosted\n'
            '    version: "1.0.0"')
    body = '\n'.join(entries)
    return ('# Generated by pub\n'
            '# See https://dart.dev/tools/pub/glossary#lockfile\n'
            'packages:\n'
            f'{body}\n'
            'sdks:\n'
            '  dart: ">=3.4.0 <4.0.0"\n')


class CheckDependenciesTest(unittest.TestCase):
    def run_check(self, lock_text: str | None, lockname: str = 'pubspec.lock'
                  ) -> subprocess.CompletedProcess[str]:
        """Run the check with a temp lockfile (None: no file at all)."""
        with tempfile.TemporaryDirectory(prefix='dep-check-') as tmp:
            lock = Path(tmp) / lockname
            if lock_text is not None:
                lock.write_text(lock_text, encoding='utf-8')
            return subprocess.run(
                [sys.executable, '-I', str(CHECK), '--lockfile', str(lock)],
                capture_output=True, text=True, check=False)

    def test_clean_lock_passes(self) -> None:
        result = self.run_check(lockfile(*ALLOWED))
        output = result.stdout + result.stderr
        self.assertEqual(result.returncode, 0, output)
        self.assertIn('PASS', result.stdout)
        self.assertEqual(len(result.stdout.strip().splitlines()), 1)

    def test_forbidden_package_fails(self) -> None:
        for forbidden in ('dart_monty', 'dart_monty_extras'):
            with self.subTest(forbidden=forbidden):
                result = self.run_check(lockfile('path', forbidden, 'test'))
                output = result.stdout + result.stderr
                self.assertEqual(result.returncode, 1, output)
                self.assertIn(forbidden, output)
                self.assertIn('forbidden', output)

    def test_unlisted_package_fails(self) -> None:
        result = self.run_check(lockfile('path', 'some_third_party_pkg'))
        output = result.stdout + result.stderr
        self.assertEqual(result.returncode, 1, output)
        self.assertIn('some_third_party_pkg', output)
        self.assertIn('allowlist', output)

    def test_missing_lock_fails(self) -> None:
        result = self.run_check(None)
        output = result.stdout + result.stderr
        self.assertEqual(result.returncode, 1, output)
        self.assertIn('missing', output)

    def test_empty_packages_block_fails(self) -> None:
        result = self.run_check('packages:\nsdks:\n  dart: ">=3.4.0 <4.0.0"\n')
        output = result.stdout + result.stderr
        self.assertEqual(result.returncode, 1, output)
        self.assertIn('no packages', output)


    def test_key_after_packages_block_not_collected(self) -> None:
        """A package-shaped key after the `packages:` block is not a package.

        The trailing `sdks:` block only ever holds `dart: ">=3.x"` values,
        which can never match the bare-key pattern, so by itself it proves
        nothing about block termination. This lockfile adds a top-level
        `extra:` section whose bare `  dart_monty:` key *does* match the
        pattern -- and names a forbidden package, so a parser that ran
        past the end of `packages:` would collect it and fail the check.
        """
        lock = lockfile('path') + 'extra:\n  dart_monty:\n'
        result = self.run_check(lock)
        output = result.stdout + result.stderr
        self.assertEqual(result.returncode, 0, output)
        self.assertIn('PASS', result.stdout)


if __name__ == '__main__':
    unittest.main()
