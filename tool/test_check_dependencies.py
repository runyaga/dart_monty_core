#!/usr/bin/env python3
"""Tests for tool/check_dependencies.py (shared dependency-check contract).

Every test runs the checker as a subprocess against files written into a
temporary directory and asserts the exit code and the exact stdout and
stderr. The allowlist under test is the committed one,
tool/dependency_allowlist.txt, unless a test writes its own.

dart_monty_core's policy row is FORBIDDEN = {dart_monty, dart_monty_extras}
with no FORBIDDEN_PREFIXES and an empty PREFIX_EXEMPT, so contract item
15 (a prefixed name failing with `direction`) belongs to
dart_monty_extras only and is replaced here by the dart_monty_core
form: a `dart_monty`-prefixed name breaks only the allowlist rule and
passes once listed. Item 16 runs the checker against the repository's
real pubspec.lock when `dart pub get` has produced one.

Usage: python3 -m unittest tool/test_check_dependencies.py -v
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECK = ROOT / 'tool' / 'check_dependencies.py'
COMMITTED_ALLOWLIST = ROOT / 'tool' / 'dependency_allowlist.txt'
REAL_LOCKFILE = ROOT / 'pubspec.lock'

# The two names forbidden for dart_monty_core (its policy row).
FORBIDDEN = ('dart_monty', 'dart_monty_extras')


def entry(name: str, dependency: str = 'transitive') -> str:
    """One pubspec.lock package entry with the given `dependency:` kind."""
    return (f'  {name}:\n'
            f'    dependency: {dependency}\n'
            '    description:\n'
            f'      name: {name}\n'
            '      url: "https://pub.dev"\n'
            '    source: hosted\n'
            '    version: "1.0.0"\n')


def lock(*entries: str) -> str:
    """A pubspec.lock-shaped text resolving exactly the given entries."""
    return ('# Generated by pub\n'
            '# See https://dart.dev/tools/pub/glossary#lockfile\n'
            'packages:\n'
            + ''.join(entries)
            + 'sdks:\n'
            '  dart: ">=3.0.0 <4.0.0"\n')


def pass_line(count: int) -> str:
    return f'PASS: {count} resolved packages allowed\n'


def direction_line(name: str) -> str:
    return (f'FAIL direction {name}: '
            f'forbidden dependency direction ({name} is in FORBIDDEN)\n')


def allowlist_line(name: str) -> str:
    return (f'FAIL allowlist {name}: '
            'resolved but not in the dependency allowlist\n')


def input_line(path: Path, reason: str) -> str:
    return f'FAIL input {path}: {reason}\n'


class CheckDependenciesTest(unittest.TestCase):
    maxDiff = None

    def run_check(self, lock_text: str | None = None, *,
                  lock_bytes: bytes | None = None,
                  allowlist_text: str | None = None,
                  ) -> tuple[subprocess.CompletedProcess[str], Path, Path | None]:
        """Run the checker over a temp pubspec.lock.

        `lock_text` (or raw `lock_bytes`) is written to a fresh
        pubspec.lock; None writes nothing. Without `allowlist_text` the
        checker's default --allowlist, the committed allowlist, is used.
        Returns (process, lockfile path, allowlist path or None).
        """
        with tempfile.TemporaryDirectory(prefix='dep-check-') as tmp:
            tmpdir = Path(tmp)
            lock_path = tmpdir / 'pubspec.lock'
            if lock_text is not None:
                lock_path.write_text(lock_text, encoding='utf-8')
            elif lock_bytes is not None:
                lock_path.write_bytes(lock_bytes)
            command = [sys.executable, '-I', str(CHECK),
                       '--lockfile', str(lock_path)]
            allowlist_path = None
            if allowlist_text is not None:
                allowlist_path = tmpdir / 'dependency_allowlist.txt'
                allowlist_path.write_text(allowlist_text, encoding='utf-8')
                command += ['--allowlist', str(allowlist_path)]
            result = subprocess.run(command, capture_output=True, text=True,
                                    check=False)
        return result, lock_path, allowlist_path

    # 1. A clean lock covering every dependency kind passes.
    def test_clean_lock_with_every_dependency_kind_passes(self) -> None:
        result, _, _ = self.run_check(lock(
            entry('args', '"direct main"'),
            entry('test', '"direct dev"'),
            entry('path', 'transitive'),
            entry('uuid', '"direct overridden"'),
        ))
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, pass_line(4))
        self.assertEqual(result.stderr, '')

    # 2a. A forbidden package fails with `direction` (being unlisted in
    # the committed allowlist, it also breaks rule 2 -- checked independently).
    def test_forbidden_package_fails_with_direction(self) -> None:
        for name in FORBIDDEN:
            with self.subTest(name=name):
                result, _, _ = self.run_check(
                    lock(entry('path'), entry(name)))
                self.assertEqual(result.returncode, 1)
                self.assertEqual(result.stdout, '')
                self.assertEqual(result.stderr,
                                 direction_line(name) + allowlist_line(name))

    # 2b. With the forbidden name in the allowlist it still fails, and
    # only with `direction`.
    def test_forbidden_in_allowlist_still_fails_direction_only(self) -> None:
        for name in FORBIDDEN:
            with self.subTest(name=name):
                result, _, _ = self.run_check(
                    lock(entry('path'), entry(name), entry('test')),
                    allowlist_text=f'path\n{name}\ntest\n')
                self.assertEqual(result.returncode, 1)
                self.assertEqual(result.stdout, '')
                self.assertEqual(result.stderr, direction_line(name))

    # 3. An unlisted package fails with `allowlist`.
    def test_unlisted_package_fails_with_allowlist(self) -> None:
        result, _, _ = self.run_check(
            lock(entry('path'), entry('totally_unlisted_pkg')))
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr, allowlist_line('totally_unlisted_pkg'))

    # 4. A package that is both forbidden and unlisted gives two findings.
    def test_forbidden_and_unlisted_gives_two_findings(self) -> None:
        result, _, _ = self.run_check(
            lock(entry('path'), entry('dart_monty_extras')))
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         direction_line('dart_monty_extras')
                         + allowlist_line('dart_monty_extras'))
        self.assertEqual(len(result.stderr.splitlines()), 2)

    # 5. An allowlist entry that resolves to nothing passes.
    def test_unused_allowlist_entry_passes(self) -> None:
        # The committed allowlist also holds names no small lock resolves
        # (uuid and dozens more), which must not be findings.
        result, _, _ = self.run_check(lock(entry('path')))
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, pass_line(1))
        self.assertEqual(result.stderr, '')

    # 6. A column-0 comment inside the package block does not end the
    # scan: a forbidden package after it still fails.
    def test_column0_comment_inside_block_does_not_end_scan(self) -> None:
        lock_text = ('packages:\n'
                     + entry('path', '"direct main"')
                     + '# a column-0 comment inside the block\n'
                     + entry('dart_monty')
                     + 'sdks:\n  dart: ">=3.0.0 <4.0.0"\n')
        result, _, _ = self.run_check(lock_text)
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         direction_line('dart_monty')
                         + allowlist_line('dart_monty'))

    # 7. A package key with a trailing comment or trailing spaces is read.
    def test_key_with_trailing_comment_or_spaces_is_read(self) -> None:
        lock_text = ('packages:\n'
                     '  path: # trailing comment\n'
                     '    dependency: "direct main"\n'
                     '  test:   \n'
                     '    dependency: "direct dev"\n'
                     'sdks:\n  dart: ">=3.0.0 <4.0.0"\n')
        result, _, _ = self.run_check(lock_text)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, pass_line(2))
        self.assertEqual(result.stderr, '')

    # 8. An indented `packages:` under another key is not a package block.
    def test_indented_packages_is_not_a_block(self) -> None:
        result, lock_path, _ = self.run_check(
            'sdks:\n  packages:\n    dart: ">=3.0.0 <4.0.0"\n')
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         input_line(lock_path,
                                    "lockfile has no 'packages:' block"))

    # 9. A second top-level `packages:` block is an input failure.
    def test_second_top_level_packages_block_is_input_error(self) -> None:
        lock_text = ('packages:\n' + entry('path')
                     + 'sdks:\n  dart: ">=3.0.0 <4.0.0"\n'
                     + 'packages:\n' + entry('test'))
        result, lock_path, _ = self.run_check(lock_text)
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         input_line(lock_path,
                                    "lockfile has more than one "
                                    "'packages:' block"))

    # 10a. A duplicate package key in the lock is an input failure.
    def test_duplicate_package_key_is_input_error(self) -> None:
        result, lock_path, _ = self.run_check(
            'packages:\n' + entry('path', '"direct main"') + entry('path'))
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         input_line(lock_path,
                                    "lockfile has a duplicate package key "
                                    "'path'"))

    # 10b. A duplicate entry in the allowlist is an input failure.
    def test_duplicate_allowlist_entry_is_input_error(self) -> None:
        result, _, allowlist_path = self.run_check(
            lock(entry('path')), allowlist_text='path\npath\n')
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         input_line(allowlist_path,
                                    "allowlist has a duplicate entry "
                                    "'path'"))

    # 11a. A malformed allowlist entry is an input failure.
    def test_malformed_allowlist_entry_is_input_error(self) -> None:
        result, _, allowlist_path = self.run_check(
            lock(entry('path')), allowlist_text='path\nNot-Valid\n')
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         input_line(allowlist_path,
                                    "allowlist has a malformed entry "
                                    "'Not-Valid'"))

    # 11b. A trailing `#` comment on an entry is accepted.
    def test_trailing_comment_on_allowlist_entry_is_accepted(self) -> None:
        result, _, _ = self.run_check(
            lock(entry('path')), allowlist_text='path # pre-approved\n')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, pass_line(1))
        self.assertEqual(result.stderr, '')

    # 12a. A missing lock gives one input line and exit 1, no traceback.
    def test_missing_lock_is_one_input_line(self) -> None:
        result, lock_path, _ = self.run_check(None)
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         input_line(lock_path,
                                    'lockfile is missing or unreadable'))
        self.assertNotIn('Traceback', result.stderr)

    # 12b. An empty package block gives one input line and exit 1.
    def test_empty_packages_block_is_one_input_line(self) -> None:
        result, lock_path, _ = self.run_check(
            'packages:\nsdks:\n  dart: ">=3.0.0 <4.0.0"\n')
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         input_line(lock_path,
                                    "lockfile has an empty 'packages:' "
                                    'block'))
        self.assertNotIn('Traceback', result.stderr)

    # 12c. A non-UTF-8 lock gives one input line and exit 1.
    def test_non_utf8_lock_is_one_input_line(self) -> None:
        result, lock_path, _ = self.run_check(
            lock_bytes=b'packages:\n  p\xffth:\n    dependency: transitive\n')
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr,
                         input_line(lock_path,
                                    'lockfile is not valid UTF-8'))
        self.assertNotIn('Traceback', result.stderr)

    # 13. A relative --lockfile resolves against --root.
    def test_relative_lockfile_resolves_against_root(self) -> None:
        with tempfile.TemporaryDirectory(prefix='dep-check-root-') as tmp:
            root = Path(tmp)
            (root / 'tool').mkdir()
            (root / 'pubspec.lock').write_text(
                lock(entry('path'), entry('test'), entry('args')),
                encoding='utf-8')
            (root / 'tool' / 'dependency_allowlist.txt').write_text(
                'args\npath\ntest\n', encoding='utf-8')
            result = subprocess.run(
                [sys.executable, '-I', str(CHECK),
                 '--root', str(root),
                 '--lockfile', 'pubspec.lock',
                 '--allowlist', 'tool/dependency_allowlist.txt'],
                capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        # Distinctive count: resolving against the wrong place (cwd or
        # the script's default root) cannot produce this exact line.
        self.assertEqual(result.stdout, pass_line(3))
        self.assertEqual(result.stderr, '')

    # 15. Contract item 15 (a prefixed name failing with `direction`) is
    # scoped to dart_monty_extras, the only row with FORBIDDEN_PREFIXES.
    # dart_monty_core's row has none (and an empty PREFIX_EXEMPT), so
    # this repo gets the other side of the rule: a `dart_monty`-prefixed
    # name is no direction violation -- it breaks only the allowlist
    # rule, and it passes once listed.
    def test_prefixed_name_is_not_forbidden_here(self) -> None:
        result, _, _ = self.run_check(
            lock(entry('path'), entry('dart_monty_foo')))
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '')
        self.assertEqual(result.stderr, allowlist_line('dart_monty_foo'))

    def test_prefixed_name_passes_once_allowlisted(self) -> None:
        result, _, _ = self.run_check(
            lock(entry('path'), entry('dart_monty_foo')),
            allowlist_text='path\ndart_monty_foo\n')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, pass_line(2))
        self.assertEqual(result.stderr, '')

    # 14. The committed allowlist is sorted and free of duplicates.
    def test_committed_allowlist_is_sorted_and_duplicate_free(self) -> None:
        text = COMMITTED_ALLOWLIST.read_text(encoding='utf-8')
        self.assertTrue(text.endswith('\n'))
        entries = []
        for raw in text.splitlines():
            line = raw.split(' #', 1)[0].strip()
            if not line or line.startswith('#'):
                continue
            entries.append(line)
        self.assertEqual(entries, sorted(entries))
        self.assertEqual(len(entries), len(set(entries)))
        for name in entries:
            self.assertRegex(name, r'^[a-z0-9_]+$')
        for name in FORBIDDEN:
            self.assertNotIn(name, entries)

    # 16. The checker passes against the repository's real pubspec.lock
    # after `dart pub get`. The lock is a local build artifact, so the
    # test skips until `dart pub get` has generated one.
    @unittest.skipUnless(REAL_LOCKFILE.exists(),
                         'pubspec.lock is absent (run dart pub get)')
    def test_checker_passes_against_real_lockfile(self) -> None:
        result = subprocess.run(
            [sys.executable, '-I', str(CHECK)],
            capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stderr, '')
        # The resolved count moves with `dart pub upgrade`, so this pins
        # the line's shape rather than the number.
        self.assertRegex(
            result.stdout, r'^PASS: [1-9][0-9]* resolved packages allowed\n$')


if __name__ == '__main__':
    unittest.main()
