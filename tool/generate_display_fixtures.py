#!/usr/bin/env python3
"""Bake the parity suite's display cases into test/unit/worker/_display_fixtures.g.dart.

usage: python3 -I tool/generate_display_fixtures.py PARITY_DIR [--check]

PARITY_DIR is a dart_monty_parity checkout (CI: the one PARITY_PIN names).
Each case of its display suite (tool/parity/cases/display/<id>.json) and
upstream's renderings recorded for it (tool/parity/expected/<id>/ref-py.json,
generated by pydantic-monty 1.1.0 and bound by the suite's manifest) become
one DisplayFixture: the code, display() in each format, the text of
display()'s refusal of an unknown format, the error class, str(), the type
and arguments of exception(), and each Frame of traceback(). Baked as Dart
constants, so the renderer and error tests read the same bytes on the VM,
dart2js and dart2wasm.

The text is passed through `dart format` (the SDK on PATH, as the gate's
format check runs it), so the committed file is format-clean.

--check writes nothing and exits 1 if the committed file differs from what
PARITY_DIR implies (the fixtures and PARITY_PIN moved apart).
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'test/unit/worker/_display_fixtures.g.dart'

HEADER = """\
// The parity suite's display cases: errors whose expected outcome records
// upstream's own renderings, generated by pydantic-monty 1.1.0 (the oracle)
// in dart_monty_parity (tool/parity/cases/display, tool/parity/expected) and
// bound by its manifest. Taken from the commit ci.yaml's PARITY_PIN names;
// the `parity` job fails if this file and that commit disagree.
//
// Generated by tool/generate_display_fixtures.py; do not edit by hand.

/// One display case and upstream's renderings of the error it raises.
final class DisplayFixture {
  const DisplayFixture(
    this.id, {
    required this.code,
    required this.traceback,
    required this.typeMsg,
    required this.msg,
    required this.badFormat,
    required this.badFormatMessage,
    required this.errorClass,
    required this.str,
    required this.exceptionType,
    required this.exceptionArgs,
    required this.frames,
  });

  /// The case's id in the parity suite.
  final String id;

  /// The code fed to a fresh session.
  final String code;

  /// `display('traceback')`.
  final String traceback;

  /// `display('type-msg')`.
  final String typeMsg;

  /// `display('msg')`.
  final String msg;

  /// A format `display()` refuses.
  final String badFormat;

  /// The text of that refusal.
  final String badFormatMessage;

  /// The error class upstream raised (`MontyRuntimeError`,
  /// `MontySyntaxError`).
  final String errorClass;

  /// `str()` of the error.
  final String str;

  /// The type of `exception()`.
  final String exceptionType;

  /// The arguments of `exception()`.
  final List<String> exceptionArgs;

  /// Each `Frame` of `traceback()`: filename, line, column, end line, end
  /// column, function name and source line.
  final List<(String, int, int, int, int, String?, String?)> frames;
}

"""


def dart_str(s: str) -> str:
    out = ["'"]
    for ch in s:
        o = ord(ch)
        if ch == '\\':
            out.append('\\\\')
        elif ch == "'":
            out.append("\\'")
        elif ch == '$':
            out.append('\\$')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif o < 0x20 or o > 0x7e:
            out.append(f'\\u{{{o:x}}}')
        else:
            out.append(ch)
    out.append("'")
    return ''.join(out)


def dart_opt(s: str | None) -> str:
    return 'null' if s is None else dart_str(s)


def render(parity: Path) -> str:
    cases = sorted((parity / 'tool/parity/cases/display').glob('*.json'))
    if not cases:
        sys.exit(f'no display cases under {parity}/tool/parity/cases/display')
    lines = [HEADER, 'const displayFixtures = <DisplayFixture>[']
    for path in cases:
        case = json.loads(path.read_text())
        cid = case['id']
        ref = json.loads((parity / 'tool/parity/expected' / cid / 'ref-py.json').read_text())
        if ref.get('runner_error') or len(ref['steps']) != 1 or 'display' not in ref['steps'][0]:
            sys.exit(f'{cid}: expected one step with a display block')
        d = ref['steps'][0]['display']
        bad = d['bad_format']
        step = ref['steps'][0]
        exc = d['exception']
        args = exc['args']
        if args.get('t') != 'tuple' or any(item.get('t') != 'str' for item in args['items']):
            sys.exit(f'{cid}: exception() args are not a tuple of str')
        lines.append(f'  DisplayFixture(\n    {dart_str(cid)},')
        for name, value in (('code', case['code']), ('traceback', d['traceback']), ('typeMsg', d['type-msg']),
                            ('msg', d['msg']), ('badFormat', bad['format']), ('badFormatMessage', bad['message']),
                            ('errorClass', step['error_class']), ('str', d['str']),
                            ('exceptionType', exc['type'])):
            lines.append(f'    {name}: {dart_str(value)},')
        lines.append('    exceptionArgs: [' + ', '.join(dart_str(item['v']) for item in args['items']) + '],')
        lines.append('    frames: [')
        for f in step['exception']['traceback']:
            fields = [dart_str(f['filename']), str(f['line']), str(f['column']), str(f['end_line']),
                      str(f['end_column']), dart_opt(f['function']), dart_opt(f['source_line'])]
            lines.append('      (' + ', '.join(fields) + '),')
        lines.append('    ],')
        lines.append('  ),')
    lines.append('];\n')
    return formatted('\n'.join(lines))


def formatted(text: str) -> str:
    # Formatted in place beside OUT, so the package's language version and page width apply.
    tmp = OUT.with_name('_display_fixtures.tmp.g.dart')
    try:
        tmp.write_text(text)
        subprocess.run(['dart', 'format', str(tmp)], cwd=ROOT, check=True, capture_output=True)
        return tmp.read_text()
    finally:
        tmp.unlink(missing_ok=True)


def main() -> int:
    args = sys.argv[1:]
    check = '--check' in args
    rest = [a for a in args if a != '--check']
    if len(rest) != 1:
        sys.exit(__doc__)
    text = render(Path(rest[0]))
    if check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'FAIL: {OUT.relative_to(ROOT)} differs from the display cases at {rest[0]}; '
                  f'regenerate with python3 -I tool/generate_display_fixtures.py {rest[0]}')
            return 1
        print(f'PASS: {OUT.relative_to(ROOT)} equals the display cases at {rest[0]}')
        return 0
    OUT.write_text(text)
    print(f'wrote {OUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
