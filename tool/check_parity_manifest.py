#!/usr/bin/env python3
"""Check tool/parity/manifest.json: every parity case is bound to its expected outcome.

The expected outcomes in tool/parity/expected are generated by the reference
oracle (tool/parity/oracle) from the cases in tool/parity/cases, with the
upstream pins in tool/upstream. The manifest records, per case, the sha256 of
the case file and of each expected outcome generated from it, per probe the
sha256 of its expected outcome, and the sha256 of the generator (the oracle's
code) and of the pins. tool/parity/oracle/check_expected.py --write
regenerates the outcomes and rewrites the manifest in the same step.

This offline check (no Python packages, no network; in the gate) fails when
  - a case was added, removed or edited without regenerating its outcome;
  - an expected outcome was added, removed or edited outside a regeneration;
  - the oracle's code or the upstream pins changed without a regeneration.
It cannot tell a hand-edited outcome whose manifest entry was hand-edited to
match; the parity-oracle CI job, which regenerates every outcome and runs
whenever any of these inputs change, catches that.

usage: python3 -I tool/check_parity_manifest.py
Exit 0 on pass, 1 on any mismatch.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CASES = ROOT / 'tool/parity/cases'
EXPECTED = ROOT / 'tool/parity/expected'
MANIFEST = ROOT / 'tool/parity/manifest.json'
GENERATOR = [
    'tool/parity/oracle/run_cases.py',
    'tool/parity/oracle/run_probes.py',
    'tool/parity/oracle/rust/Cargo.toml',
    'tool/parity/oracle/rust/Cargo.lock',
    'tool/parity/oracle/rust/src/main.rs',
]
PINS = ['tool/upstream/requirements.lock', 'tool/upstream/upstream-pin.json']


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def group(paths: list[str]) -> dict:
    files = {p: sha(ROOT / p) for p in paths}
    agg = hashlib.sha256(''.join(f'{p}\0{h}\n' for p, h in files.items()).encode()).hexdigest()
    return {'sha256': agg, 'files': files}


def compute() -> dict:
    """The manifest the tree on disk implies."""
    cases = {}
    for p in sorted(CASES.glob('*/*.json')):
        cid = p.stem
        outs = {f.stem: sha(f) for f in sorted((EXPECTED / cid).glob('*.json'))} if (EXPECTED / cid).is_dir() else {}
        cases[cid] = {'suite': p.parent.name, 'case': sha(p), 'outcomes': outs}
    probes = {}
    for d in sorted(p for p in EXPECTED.iterdir() if p.is_dir() and p.name not in cases):
        probes[d.name] = {'outcomes': {f.stem: sha(f) for f in sorted(d.glob('*.json'))}}
    return {'generator': group(GENERATOR), 'pins': group(PINS), 'cases': cases, 'probes': probes}


def main() -> int:
    want = json.loads(MANIFEST.read_text())
    got = compute()
    fails = []
    if got['generator']['sha256'] != want['generator']['sha256']:
        changed = [p for p in GENERATOR if got['generator']['files'][p] != want['generator']['files'].get(p)]
        fails.append(f'oracle code changed without regenerating the expected outcomes: {", ".join(changed)}')
    if got['pins']['sha256'] != want['pins']['sha256']:
        changed = [p for p in PINS if got['pins']['files'][p] != want['pins']['files'].get(p)]
        fails.append(f'upstream pins changed without regenerating the expected outcomes: {", ".join(changed)}')
    for cid in sorted(set(got['cases']) | set(want['cases'])):
        g, w = got['cases'].get(cid), want['cases'].get(cid)
        if w is None:
            fails.append(f'case {cid} is new: generate its expected outcome (check_expected.py --write)')
        elif g is None:
            fails.append(f'case {cid} was removed but its manifest entry was not')
        elif g['case'] != w['case']:
            fails.append(f'case {cid} changed without regenerating its expected outcome')
        elif not g['outcomes']:
            fails.append(f'case {cid} has no expected outcome')
        elif g['outcomes'] != w['outcomes']:
            fails.append(f'expected outcome of case {cid} changed outside a regeneration')
    for pid in sorted(set(got['probes']) | set(want['probes'])):
        if got['probes'].get(pid) != want['probes'].get(pid):
            fails.append(f'expected outcome of probe {pid} added, removed or changed outside a regeneration')
    for f in fails[:40]:
        print(f'FAIL: {f}')
    if fails:
        print(f'\n{len(fails)} problem(s). Regenerate with tool/parity/oracle/check_expected.py --write '
              '(see tool/parity/README.md), which rewrites the outcomes and this manifest together.')
        return 1
    n_out = sum(len(c['outcomes']) for c in got['cases'].values()) + sum(len(p['outcomes']) for p in got['probes'].values())
    print(f'PASS: {len(got["cases"])} cases and {len(got["probes"])} probes bound to {n_out} expected outcomes; '
          f'generator {got["generator"]["sha256"][:12]}, pins {got["pins"]["sha256"][:12]}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
