#!/usr/bin/env python3
"""Generate lib/src/worker/tz_names.g.dart: the IANA zone names the worker knows.

upstream's checkout refuses an unknown zone name while it parses its
arguments, before any worker is taken (pydantic_monty os_policy.rs
`time_zone` -> monty-types `SandboxTimeZone::named`, which asks jiff's tz
database). Core's parent has no tz database, so it checks the name against
this list: every name in jiff-tzdb, the copy of the IANA database compiled
into every worker (native/worker/Cargo.toml enables `tzdb-bundled`), at the
version native/worker/Cargo.lock pins.

usage:
  python3 -I tool/generate_tz_names.py            # write the file
  python3 -I tool/generate_tz_names.py --check    # offline freshness check
  python3 -I tool/generate_tz_names.py --online   # also re-derive from crates.io

The names are read from the crate's `tzname.rs`, found in Cargo's registry
(`$CARGO_HOME`, default ~/.cargo) or, with --online, downloaded from
static.crates.io and checked against the checksum in Cargo.lock.

--check exits 1 unless the file records the jiff-tzdb version and checksum
Cargo.lock pins, its names hash to the recorded hash and, when the crate
source is in the registry, they are exactly the crate's. --online always
compares against the crate.
"""

from __future__ import annotations

import hashlib
import io
import os
import re
import sys
import tarfile
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / 'native/worker/Cargo.lock'
OUT = ROOT / 'lib/src/worker/tz_names.g.dart'
CRATE = 'jiff-tzdb'
DOWNLOAD = 'https://static.crates.io/crates/{name}/{name}-{version}.crate'

NAME = re.compile(r'^\s*\(r"([^"]+)",', re.M)
TZDATA = re.compile(r'VERSION: Option<&str> = Some\(r"([^"]+)"\)')


def pinned() -> tuple[str, str]:
    """jiff-tzdb's version and checksum in native/worker/Cargo.lock."""
    lock = tomllib.loads(LOCK.read_text())
    found = [p for p in lock['package'] if p['name'] == CRATE]
    if len(found) != 1:
        raise SystemExit(f'{LOCK.relative_to(ROOT)}: expected one {CRATE}, found {len(found)}')
    return found[0]['version'], found[0]['checksum']


def from_registry(version: str) -> str | None:
    """tzname.rs from Cargo's registry, or None when it is not there."""
    home = Path(os.environ.get('CARGO_HOME', Path.home() / '.cargo'))
    for src in sorted((home / 'registry/src').glob(f'*/{CRATE}-{version}')):
        return (src / 'tzname.rs').read_text()
    return None


def from_crates_io(version: str, checksum: str) -> str:
    """tzname.rs from the published crate, whose sha256 must be [checksum]."""
    url = DOWNLOAD.format(name=CRATE, version=version)
    with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310 - fixed https URL
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != checksum:
        raise SystemExit(f'{url}: sha256 {digest}, Cargo.lock says {checksum}')
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as crate:
        member = crate.extractfile(f'{CRATE}-{version}/tzname.rs')
        if member is None:
            raise SystemExit(f'{url}: no tzname.rs')
        return member.read().decode()


def names_of(tzname_rs: str) -> tuple[list[str], str]:
    names = NAME.findall(tzname_rs)
    tzdata = TZDATA.search(tzname_rs)
    if not names or tzdata is None:
        raise SystemExit(f'{CRATE}: tzname.rs no longer has the expected shape')
    return names, tzdata.group(1)


def names_hash(names: list[str]) -> str:
    return hashlib.sha256('\n'.join(names).encode()).hexdigest()


def render(version: str, checksum: str, tzdata: str, names: list[str]) -> str:
    rows = ''.join(f"  '{n}',\n" for n in names)
    return f"""\
// The IANA zone names every worker's tz database holds: {CRATE} {version}
// (tzdata {tzdata}), as native/worker/Cargo.lock pins it.
//
// crate checksum: {checksum}
// names sha256: {names_hash(names)}
//
// Generated by tool/generate_tz_names.py; do not edit by hand.

/// The zone names, as the database spells them. A name is looked up
/// ignoring ASCII case, as the database looks it up.
const List<String> tzNames = [
{rows}];
"""


def recorded() -> tuple[str | None, str | None, list[str]]:
    text = OUT.read_text() if OUT.exists() else ''
    version = re.search(rf'// The IANA zone names .*: {CRATE} (\S+)', text)
    checksum = re.search(r'// crate checksum: (\S+)', text)
    stated = re.search(r'// names sha256: (\S+)', text)
    names = re.findall(r"^  '([^']+)',$", text, re.M)
    if stated is None or stated.group(1) != names_hash(names):
        raise SystemExit(f'{OUT.relative_to(ROOT)}: its names do not hash to the recorded sha256')
    return (version and version.group(1)), (checksum and checksum.group(1)), names


def main() -> int:
    online = '--online' in sys.argv[1:]
    check = online or '--check' in sys.argv[1:]
    version, checksum = pinned()
    source = from_crates_io(version, checksum) if online else from_registry(version)
    if not check:
        if source is None:
            raise SystemExit(f'{CRATE} {version} is not in the Cargo registry: '
                             'run `bash tool/build_worker.sh` first, or use --online')
        names, tzdata = names_of(source)
        OUT.write_text(render(version, checksum, tzdata, names))
        return 0
    rec_version, rec_checksum, rec_names = recorded()
    failures = []
    if (rec_version, rec_checksum) != (version, checksum):
        failures.append(f'records {CRATE} {rec_version} ({rec_checksum}); '
                        f'Cargo.lock pins {version} ({checksum})')
    if source is None:
        print(f'{OUT.relative_to(ROOT)}: {CRATE} {version} not in the Cargo registry; '
              'names checked against the recorded hash only (--online compares them)')
    elif names_of(source)[0] != rec_names:
        failures.append(f'its names differ from {CRATE} {version}')
    for failure in failures:
        print(f'{OUT.relative_to(ROOT)}: {failure}; regenerate with '
              'python3 -I tool/generate_tz_names.py', file=sys.stderr)
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
