#!/usr/bin/env bash
# =============================================================================
# tool/check_api_absent.sh — removed API must stay removed
# =============================================================================
# The cutover to the worker engine removed the in-process engine's public
# names (the REPL, the platform layer, the result and progress types, the
# mocks, the code-capture helpers) and renamed others to upstream's names
# (pass 3, M3). Re-adding any of them would ship a second API beside the
# worker's. This probes every removed or renamed-away public name, and the
# members the cutover removed from kept names.
#
# HOW: a probe library that references every removed name is written to a
# scratch directory inside the package (so it resolves `package:dart_monty_core`
# through this package's own package_config) and analysed. Each name must come
# back as "Undefined name '<N>'", and each member as "isn't defined for the
# type '<T>'" — that wording needs <T> to have RESOLVED, so a broken import
# cannot pass by making everything undefined. Any other analyzer ERROR fails
# the check for the same reason.
#
# WHY THE ANALYZER AND NOT GREP: a grep cannot tell a declaration from a
# comment, a doc reference or a CHANGELOG line, and misses a member re-added
# through a mixin or a superclass. The analyzer answers the real question —
# can a consumer call it — and nothing else.
#
# The probe is generated, not committed: a committed file that is SUPPOSED to
# fail analysis would need an analyzer exclusion, and an exclusion is code that
# nothing else looks at. The scratch dir is under .dart_tool/ (gitignored) and
# is removed on exit, so this writes nothing the gate's read-only check sees.
#
# Usage: bash tool/check_api_absent.sh
# =============================================================================
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 2

PROBE_DIR=".dart_tool/api_absence_probe.$$"
mkdir -p "$PROBE_DIR" || exit 2
trap 'rm -rf "$PROBE_DIR"' EXIT
PROBE="$PROBE_DIR/probe.dart"

# Public names the cutover removed or renamed away, one per line.
NAMES='assignmentPattern
captureLastExpression
createPlatformMonty
defaultMemoryUsageLimit
entryMemoryUsage
extractAssignmentTargets
formatBytesPretty
inputsToCode
isExpression
MockCallHistory
MockMontyPlatform
MontyCallback
MontyClassInstance
MontyClassType
MontyCrashError
MontyDataclass
MontyDisposedError
MontyException
MontyFutureCapable
MontyInternalError
MontyLimits
MontyNameLookup
MontyOpaque
MontyOpaqueKind
MontyOsCall
MontyPanicError
MontyPending
MontyPlatform
MontyProgress
MontyRepl
MontyResolveFutures
MontyResourceError
MontyResourceUsage
MontyResult
MontyScriptError
MontyStackFrame
MontySuspensionBudgetExceeded
OsCallException
OsCallHandler
osCallNoHandlerDefault
ReplContinuationMode
ReplPlatform
statementPrefixes
toPythonLiteral
VfsDir
VfsNode
MontyPool
PoolSession
PoolOptions
SessionConfig
SessionComplete'

# <Type>.<member> — members removed from kept public types. Each must be
# reported as undefined on exactly that type.
EXPECTED='Monty.run
Monty.exec
Monty.typeCheck
Monty.scriptName
Monty.dispose
MontyError.message
MontyCrashedError.cause
MontyCrashedError.detail
MontyCrashedError.exitCode
MontyCrashedError.stderrTail
SourceRange.unknown'

{
  cat <<'DART'
// GENERATED by tool/check_api_absent.sh. Every reference below must FAIL to
// resolve; see that script.
import 'package:dart_monty_core/dart_monty_core.dart';
import 'package:dart_monty_core/dart_monty_core_testing.dart';

DART
  echo 'List<Object?> probe('
  for t in $(echo "$EXPECTED" | cut -d. -f1 | sort -u); do
    echo "  $t p$t,"
  done
  echo ') => ['
  echo "$NAMES" | while read -r n; do echo "  $n,"; done
  echo "$EXPECTED" | while IFS=. read -r t m; do echo "  p$t.$m,"; done
  echo '];'
} > "$PROBE"

OUT="$(dart analyze --format=machine "$PROBE" 2>&1)"

# Machine format: SEVERITY|TYPE|CODE|FILE|LINE|COL|LEN|MESSAGE
ERRORS="$(echo "$OUT" | grep -E '^ERROR\|' || true)"

FAILED=0
COUNT=0
while read -r n; do
  COUNT=$((COUNT + 1))
  if ! echo "$ERRORS" | grep -qF "Undefined name '$n'"; then
    echo "  FAIL  $n resolves through the public libraries: a removed name"
    echo "        is back, or the probe broke (any error listed below)."
    FAILED=$((FAILED + 1))
  fi
done <<< "$NAMES"
while IFS=. read -r t m; do
  COUNT=$((COUNT + 1))
  if ! echo "$ERRORS" | grep -qF "'$m' isn't defined for the type '$t'"; then
    echo "  FAIL  $t.$m is not reported undefined on $t: the removed member"
    echo "        is back, or the probe broke (any error listed below)."
    FAILED=$((FAILED + 1))
  fi
done <<< "$EXPECTED"

# Anything else is a broken probe, not a pass: an unresolved import or type
# would otherwise make every reference "undefined" for the wrong reason.
OTHER="$(echo "$ERRORS" | grep -vF "isn't defined for the type '" | grep -vF "Undefined name '" | grep . || true)"
if [ -n "$OTHER" ]; then
  echo "  FAIL  the probe itself did not analyse cleanly:"
  echo "$OTHER" | sed 's/^/        /'
  FAILED=$((FAILED + 1))
fi

if [ "$FAILED" -gt 0 ]; then
  echo "FAIL — $FAILED problem(s); probe was $PROBE:"
  sed 's/^/    /' "$PROBE"
  exit 1
fi

echo "PASS — $COUNT removed names and members are undefined."
