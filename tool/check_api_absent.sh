#!/usr/bin/env bash
# =============================================================================
# tool/check_api_absent.sh — removed API must stay removed
# =============================================================================
# The precompile API (`Monty.compile`, `Monty.runPrecompiled`,
# `MontyPlatform.compileCode` / `runPrecompiled` / `startPrecompiled`) was
# removed because it could never work: it snapshots the one-shot handle, and
# native/src/handle.rs refuses that unconditionally on every target (core#152).
# It was green in CI for its whole life because the only tests ran against
# MockMontyPlatform. Re-adding any of it would re-ship that dead surface.
#
# HOW: a probe library that references every removed name is written to a
# scratch directory inside the package (so it resolves `package:dart_monty_core`
# through this package's own package_config) and analysed. Every reference must
# come back as "isn't defined for the type '<T>'" — that wording needs <T> to
# have RESOLVED, so a broken import cannot pass by making everything undefined.
# Any other analyzer ERROR fails the check for the same reason.
#
# WHY THE ANALYZER AND NOT GREP: a grep cannot tell a declaration from a
# comment, a doc reference or a CHANGELOG line, and misses a member re-added
# through a mixin or a superclass. The analyzer answers the real question —
# can a consumer call it — and nothing else.
#
# The probe is generated, not committed: a committed file that is SUPPOSED to
# fail analysis would need an analyzer exclusion, and an exclusion is code that
# nothing else looks at. The scratch dir is under .dart_tool/ (gitignored) and
# is removed on exit, so this writes nothing the gate's read-only check sees.
#
# Usage: bash tool/check_api_absent.sh
# =============================================================================
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 2

PROBE_DIR=".dart_tool/api_absence_probe.$$"
mkdir -p "$PROBE_DIR" || exit 2
trap 'rm -rf "$PROBE_DIR"' EXIT
PROBE="$PROBE_DIR/probe.dart"

# <Type>.<member> — one line per removed name, per type that carried it.
# Each must be reported as undefined on exactly that type.
EXPECTED='Monty.compile
Monty.runPrecompiled
MontyPlatform.compileCode
MontyPlatform.runPrecompiled
MontyPlatform.startPrecompiled
MockMontyPlatform.compileCode
MockMontyPlatform.runPrecompiled
MockMontyPlatform.startPrecompiled
MockCallHistory.compileCodeList
MockCallHistory.runPrecompiledDataList
MockCallHistory.startPrecompiledDataList
MockCallHistory.lastCompileCode
MockCallHistory.lastRunPrecompiledData
MockCallHistory.lastStartPrecompiledData
ReplPlatform.compileCode
ReplPlatform.runPrecompiled
ReplPlatform.startPrecompiled
MontyFfi.compileCode
MontyFfi.runPrecompiled
MontyFfi.startPrecompiled
MontyWasm.compileCode
MontyWasm.runPrecompiled
MontyWasm.startPrecompiled
MontyCoreBindings.compileCode
MontyCoreBindings.runPrecompiled
MontyCoreBindings.startPrecompiled
FfiCoreBindings.compileCode
FfiCoreBindings.runPrecompiled
FfiCoreBindings.startPrecompiled
WasmCoreBindings.compileCode
WasmCoreBindings.runPrecompiled
WasmCoreBindings.startPrecompiled
WasmBindings.compile
WasmBindings.runPrecompiled
WasmBindings.startPrecompiled'

{
  cat <<'DART'
// GENERATED by tool/check_api_absent.sh. Every reference below must FAIL to
// resolve; see that script.
import 'package:dart_monty_core/dart_monty_core.dart';
import 'package:dart_monty_core/src/ffi/ffi_core_bindings.dart';
import 'package:dart_monty_core/src/ffi/monty_ffi.dart';
import 'package:dart_monty_core/src/platform/mock_monty_platform.dart';
import 'package:dart_monty_core/src/platform/monty_core_bindings.dart';
import 'package:dart_monty_core/src/wasm/monty_wasm.dart';
import 'package:dart_monty_core/src/wasm/wasm_bindings.dart';
import 'package:dart_monty_core/src/wasm/wasm_core_bindings.dart';

DART
  echo 'List<Object?> probe('
  # One parameter per instance type; `Monty` is probed statically.
  for t in $(echo "$EXPECTED" | cut -d. -f1 | sort -u | grep -vx Monty); do
    echo "  $t p$t,"
  done
  echo ') => ['
  echo "$EXPECTED" | while IFS=. read -r t m; do
    if [ "$t" = Monty ]; then
      echo "  Monty.$m,"
    else
      echo "  p$t.$m,"
    fi
  done
  echo '];'
} > "$PROBE"

OUT="$(dart analyze --format=machine "$PROBE" 2>&1)"

# Machine format: SEVERITY|TYPE|CODE|FILE|LINE|COL|LEN|MESSAGE
ERRORS="$(echo "$OUT" | grep -E '^ERROR\|' || true)"

FAILED=0
COUNT=0
while IFS=. read -r t m; do
  COUNT=$((COUNT + 1))
  if ! echo "$ERRORS" | grep -qF "'$m' isn't defined for the type '$t'"; then
    echo "  FAIL  $t.$m is not reported undefined on $t: the removed API is"
    echo "        back (core#152), or the probe broke (any error listed below)."
    FAILED=$((FAILED + 1))
  fi
done <<< "$EXPECTED"

# Anything else is a broken probe, not a pass: an unresolved import or type
# would otherwise make every reference "undefined" for the wrong reason.
OTHER="$(echo "$ERRORS" | grep -vF "isn't defined for the type '" | grep . || true)"
if [ -n "$OTHER" ]; then
  echo "  FAIL  the probe itself did not analyse cleanly:"
  echo "$OTHER" | sed 's/^/        /'
  FAILED=$((FAILED + 1))
fi

if [ "$FAILED" -gt 0 ]; then
  echo "FAIL — $FAILED problem(s); probe was $PROBE:"
  sed 's/^/    /' "$PROBE"
  exit 1
fi

echo "PASS — $COUNT removed precompile names are undefined on their types."
