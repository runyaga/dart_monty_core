#!/usr/bin/env python3
"""Record upstream's outcome for each OS-handler case into test/unit/worker/_os_handler_oracle.g.dart.

usage: PYTHON -I tool/generate_os_handler_oracle.py [--check]

PYTHON is an interpreter with the pydantic-monty that tool/upstream/requirements.lock pins installed (the oracle).
Each case runs one snippet with `feed_run` on a checkout of upstream's
AsyncMonty whose `os_policy` routes the clock and sleeps to the host
(`{'datetime': 'call_host', 'sleep': 'call_host'}`), answered by one `os=`
handler. The Dart side (test/unit/worker/_os_handler_cases.dart) builds the
same handler as an OsHandler and must reach the same outcomes on the VM,
dart2js and dart2wasm.

A case is (id, handler, code). The handler is one of:
- 'decline': returns NOT_HANDLED (Dart: throws OsCallNotHandledException);
- 'async_decline': a coroutine that returns NOT_HANDLED (Dart: a Future
  that fails with OsCallNotHandledException);
- 'async_value': a coroutine that returns 'v' (Dart: a Future of
  MontyString('v'));
- 'async_raise': a coroutine that raises ValueError('x') (Dart: a Future
  that fails with ExternalException('ValueError', 'x')).

An outcome is `value: <repr>` or `<ErrorClass>: <display('type-msg')>`.
Upstream names its Python classes in a conversion failure; the Dart side
names its own (NAMES in _os_handler_cases.dart).

--check writes nothing and exits 1 if the committed file differs.
"""

from __future__ import annotations

import asyncio
import subprocess
import sys
from pathlib import Path
from typing import Any

import pydantic_monty as pm

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'test/unit/worker/_os_handler_oracle.g.dart'

POLICY = {'datetime': 'call_host', 'sleep': 'call_host'}

CODES = {
    'read_text': "from pathlib import Path\nPath('/a.txt').read_text()",
    'getenv': "import os\nos.getenv('X')",
    'now': 'import datetime\nstr(datetime.datetime.now())',
    'time_sleep': 'import time\ntime.sleep(0.01)',
    # Awaited at once with nothing else to run: an eager answer.
    'async_sleep_eager': "import asyncio\nawait asyncio.sleep(0.01, 'r')",
    # Two at once: each answered with a future, settled later.
    'async_sleep_gather': (
        'import asyncio\n'
        'async def f():\n'
        "    return await asyncio.sleep(0.01, 'r')\n"
        'await asyncio.gather(f(), f())'
    ),
}


def decline(**_: Any) -> Any:
    return pm.NOT_HANDLED


async def async_decline(**_: Any) -> Any:
    return pm.NOT_HANDLED


async def async_value(**_: Any) -> Any:
    return 'v'


async def async_raise(**_: Any) -> Any:
    raise ValueError('x')


HANDLERS = {
    'decline': decline,
    'async_decline': async_decline,
    'async_value': async_value,
    'async_raise': async_raise,
}

CASES = [(f'{code}/{handler}', handler, code) for code in CODES for handler in HANDLERS]


async def outcome(pool: Any, handler: str, code: str) -> str:
    async with pool.checkout(os_policy=POLICY) as session:
        try:
            return f'value: {await session.feed_run(CODES[code], os=HANDLERS[handler])!r}'
        except pm.MontyError as e:
            return f'{type(e).__name__}: {e.display("type-msg")}'


async def record() -> list[tuple[str, str, str, str]]:
    async with pm.AsyncMonty(max_processes=1) as pool:
        return [(case_id, handler, code, await outcome(pool, handler, code)) for case_id, handler, code in CASES]


def dart_str(s: str) -> str:
    out = ["'"]
    for ch in s:
        o = ord(ch)
        if ch == '\\':
            out.append('\\\\')
        elif ch == "'":
            out.append("\\'")
        elif ch == '$':
            out.append('\\$')
        elif ch == '\n':
            out.append('\\n')
        elif o < 0x20 or o == 0x7F or o > 0x7E:
            out.append(f'\\u{{{o:x}}}')
        else:
            out.append(ch)
    out.append("'")
    return ''.join(out)


HEADER = """\
// Upstream's outcome for each OS-handler case, recorded from pydantic-monty
// 1.1.0 (the oracle) by tool/generate_os_handler_oracle.py, which also holds
// the Python form of each case and the meaning of each handler. The Dart
// form of each is in _os_handler_cases.dart.
//
// An outcome is `value: <repr>` or `<ErrorClass>: <display('type-msg')>`.
//
// Generated by tool/generate_os_handler_oracle.py; do not edit by hand.

/// The snippet each case runs, by name.
const Map<String, String> osHandlerCodes = {
"""


def render(recorded: list[tuple[str, str, str, str]]) -> str:
    codes = ''.join(f'  {dart_str(k)}: {dart_str(v)},\n' for k, v in CODES.items())
    cases = ''.join(
        f'  {dart_str(case_id)}: (handler: {dart_str(handler)}, code: {dart_str(code)}, '
        f'outcome: {dart_str(o)}),\n'
        for case_id, handler, code, o in recorded
    )
    text = (
        HEADER
        + codes
        + '};\n\n/// Per case id: the handler, the snippet and upstream\'s outcome.\n'
        + 'const Map<String, ({String handler, String code, String outcome})>\nosHandlerOracle = {\n'
        + cases
        + '};\n'
    )
    formatted = subprocess.run(
        ['dart', 'format', '--stdin-name', str(OUT)],
        input=text,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return formatted.stdout


def main() -> int:
    check = '--check' in sys.argv[1:]
    text = render(asyncio.run(record()))
    if check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT.relative_to(ROOT)} differs from the oracle', file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
