#!/usr/bin/env python3
"""Score dart_monty_core's parity outcomes against pydantic-monty's, per capability row.

usage:
  python3 -I tool/parity/score.py OUTCOMES [--backends vm,dart2js,dart2wasm]
         [--expected DIR] [--json FILE] [--markdown FILE]
         [--assert-baseline] [--assert-rows]

OUTCOMES holds core-<backend>.json per case (tool/parity/run.py) and, for the
probe suites, per probe. EXPECTED (default tool/parity/expected) holds the
upstream's outcomes, generated by the reference oracle (pydantic-monty at the
tool/upstream pin) and bound to the cases by tool/parity/manifest.json.

Each case cell is classed MATCH (every compared field equals the oracle's),
DIVERGE, REFUSED (core refused what the case asked: a refusal the row's rule
names, or limits core declined), NO-OUTCOME (the runner produced nothing) or
NO-ORACLE. A row's status on a backend follows from its cases
(tool/parity/rows.json):

  PRESENT  every case MATCH
  PARTIAL  some, not all, MATCH
  ABSENT   none MATCH
  REFUSED  every case REFUSED

A row rule may carry named exceptions: a tolerated difference, each with its
reason. Nothing else is tolerated.

--assert-rows fails when a re-measured row's status differs from the status
recorded for it in rows.json under the backend's `expect` (the baseline
measured at dart_monty_core 5873ec5); --assert-baseline fails when the FFI
PRESENT count over the 185 in-scope manifest rows differs from the manifest's
frozen baseline (re-measured rows from this run, the rest as recorded).

Expectations are per CPU architecture. The baseline was measured on arm64;
`platforms` in rows.json (and in the current-baseline file) lists, per other
architecture, the rows whose status measurably differs there and that
architecture's PRESENT totals, each with its cause. The architecture comes
from OUTCOMES/platform.json, written by tool/parity/run.py; an architecture
with no entry fails.

--assert-current FILE compares instead with the baseline recorded for the
current tree (tool/parity/baseline-current.json): every re-measured row on
every backend, and the totals. A change that moves a row updates that file,
with the move listed under `deltas`.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RULES = ROOT / 'tool/parity/rows.json'
MANIFEST = ROOT / 'tool/upstream/capability-manifest.tsv'
META = ROOT / 'tool/upstream/capability-manifest.json'
CASES = ROOT / 'tool/parity/cases'

UUID = re.compile(r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}')
NUM = re.compile(r'\d+(\.\d+)?')
ALL_CODES = ['V', 'E', 'P', 'O', 'X', 'H', 'C']
E_PARTS = ['Et', 'Em', 'Ef', 'Ed']  # exception type, message, frames, structured data
FIELD = {'V': 'value', 'P': 'prints', 'O': 'os_calls', 'X': 'ext_calls', 'H': 'host_calls'}
CONFIG_KEYS = ('inputs', 'limits', 'os_policy', 'fs', 'cwd', 'mount_close')


# ------------------------------------------------------------------ compare
def norm(v):
    """Re-sorts sets, drops display-only float text, hidden `_` keys, uuids and measured limit amounts."""
    if isinstance(v, str):
        v = UUID.sub('<uuid>', v)
        return NUM.sub('N', v) if 'limit exceeded: ' in v else v
    if isinstance(v, list):
        return [norm(x) for x in v]
    if isinstance(v, dict):
        if v.get('t') == 'float':
            return {'t': 'float', 'bits': v.get('bits')}
        d = {k: norm(x) for k, x in v.items() if not k.startswith('_')}
        if d.get('t') in ('set', 'frozenset'):
            d['items'] = sorted(d['items'], key=lambda e: json.dumps(e, sort_keys=True))
        return d
    return v


def exc_part(e, part):
    if not e:
        return e
    return e.get({'Et': 'type', 'Em': 'message', 'Ef': 'traceback', 'Ed': 'data'}[part])


def expand(codes: list[str]) -> list[str]:
    """`E` stands for all four exception parts."""
    out = []
    for c in codes:
        out.extend(E_PARTS if c == 'E' else [c])
    return out


def _opaque_as_str(v):
    """{opaque, text} -> {str, text}: core types repr/cycle/function placeholders; upstream returns the str."""
    if isinstance(v, list):
        return [_opaque_as_str(x) for x in v]
    if isinstance(v, dict):
        if v.get('t') == 'opaque':
            return {'t': 'str', 'v': v.get('v')}
        return {k: _opaque_as_str(x) for k, x in v.items()}
    return v


def _identity_inline(v, table=None):
    """Resolves id/ref identity markers, so only identity (not value) is ignored."""
    if table is None:
        table = {}

        def collect(x):
            if isinstance(x, dict):
                if 'id' in x and x.get('t') != 'ref':
                    table[x['id']] = x
                for y in x.values():
                    collect(y)
            elif isinstance(x, list):
                for y in x:
                    collect(y)

        collect(v)
    if isinstance(v, list):
        return [_identity_inline(x, table) for x in v]
    if isinstance(v, dict):
        if v.get('t') == 'ref' and v.get('id') in table:
            return _identity_inline({k: x for k, x in table[v['id']].items() if k != 'id'}, table)
        return {k: _identity_inline(x, table) for k, x in v.items() if k != 'id'}
    return v


def _drop_convert_events(v):
    """Host-call transcript without convert_value events (core has no conversion hook)."""
    if isinstance(v, list):
        return [x for x in v if not (isinstance(x, dict) and x.get('op') == 'convert')]
    return v


NORMALISERS = {
    'opaque_as_str': ('V', _opaque_as_str),
    'identity_inline': ('V', _identity_inline),
    'drop_convert_events': ('H', _drop_convert_events),
}


def compare_steps(ref: dict, got: dict, codes: list[str], normalisers: list[str] = ()) -> list[str]:
    """Codes of the compared fields that differ."""
    bad = []
    rs, gs = ref.get('steps') or [], got.get('steps') or []
    for code in codes:
        if code == 'C':
            unsup = got.get('unsupported') or {}
            if any(k.split('.')[0] in CONFIG_KEYS for k in unsup):
                bad.append('C')
            continue
        if code in E_PARTS:
            rv = [norm(exc_part(s.get('exception'), code)) for s in rs]
            gv = [norm(exc_part(s.get('exception'), code)) for s in gs]
        else:
            rv = [norm(s.get(FIELD[code])) for s in rs]
            gv = [norm(s.get(FIELD[code])) for s in gs]
            for n in normalisers:
                field, fn = NORMALISERS[n]
                if field == code:
                    rv, gv = [fn(x) for x in rv], [fn(x) for x in gv]
        if rv != gv:
            bad.append(code)
    return bad


def is_refusal(got: dict, rule: dict) -> bool:
    if got.get('refused'):
        # Core declined the case's limits; a limit core has no field for at all is ABSENT, not REFUSED.
        unsup = got.get('unsupported') or {}
        return not any(k in unsup for k in rule.get('absent_if_unsupported', []))
    for needle in (rule.get('refusal') or {}).get('message_contains', []):
        for s in got.get('steps') or []:
            e = s.get('exception') or {}
            if needle in (e.get('message') or ''):
                return True
    return False


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def classify_case(cid: str, backend: str, rule: dict, out: Path, expected: Path) -> tuple[str, list[str], list[str]]:
    """-> (class, differing codes, names of the exceptions that changed the verdict)."""
    ref = load(expected / cid / f"{rule.get('oracle', 'ref-py')}.json")
    got = load(out / cid / f'core-{backend}.json')
    if got is None or got.get('runner_error'):
        return 'NO-OUTCOME', ['!'], []
    if is_refusal(got, rule):
        return 'REFUSED', [], []
    if ref is None or ref.get('runner_error'):
        return 'NO-ORACLE', ['?'], []
    codes = expand(rule.get('compare', ALL_CODES))
    applied = []
    normalisers: list[str] = []
    for ex in rule.get('exceptions', []):
        if ex.get('case') not in (None, cid) or backend not in ex.get('backends', [backend]):
            continue
        before = compare_steps(ref, got, codes, normalisers)
        if 'normalise' in ex:
            after = compare_steps(ref, got, codes, [*normalisers, ex['normalise']])
            if after != before:
                normalisers.append(ex['normalise'])
                applied.append(ex['name'])
            continue
        ignore = set(expand(ex['ignore']))
        if ignore & set(before):  # only when the tolerated difference is actually there
            codes = [c for c in codes if c not in ignore]
            applied.append(ex['name'])
    bad = compare_steps(ref, got, codes, normalisers)
    return ('MATCH' if not bad else 'DIVERGE'), bad, applied


def row_status(classes: list[str]) -> str:
    counted = [c for c in classes if c != 'NO-ORACLE']
    if not counted:
        return 'UNVERIFIED'
    if all(c == 'REFUSED' for c in counted):
        return 'REFUSED'
    n = sum(c == 'MATCH' for c in counted)
    if n == len(counted):
        return 'PRESENT'
    return 'PARTIAL' if n else 'ABSENT'


# ------------------------------------------------------------------ probes
def probe_status(row: str, rule: dict, backend: str, out: Path, expected: Path) -> tuple[str, list[dict]]:
    """Probe suites: each probe's transcript equals the oracle's (with the row's named exceptions)."""
    from probes_compare import judge  # noqa: PLC0415 (local module, same dir)

    cells = []
    for pid in rule['probes']:
        ref = load(expected / pid / f"{rule.get('oracle', 'ref-py')}.json")
        got = load(out / pid / f'core-{backend}.json')
        cls, why, applied = judge(pid, ref, got, rule)
        cells.append({'case': pid, 'class': cls, 'differs': why, 'exceptions': applied})
    return row_status([c['class'] for c in cells]), cells


# ------------------------------------------------------------------ main
def platform_arch(outcomes: Path) -> str:
    p = outcomes / 'platform.json'
    if not p.exists():
        sys.exit(f'{p} is missing: run tool/parity/run.py, which records the platform it measured on')
    return json.loads(p.read_text())['arch']



def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('outcomes', type=Path)
    ap.add_argument('--backends', default='vm,dart2js,dart2wasm')
    ap.add_argument('--expected', type=Path, default=ROOT / 'tool/parity/expected')
    ap.add_argument('--json', type=Path)
    ap.add_argument('--markdown', type=Path)
    ap.add_argument('--assert-rows', action='store_true')
    ap.add_argument('--assert-baseline', action='store_true')
    ap.add_argument('--assert-current', type=Path)
    ap.add_argument('--write-current', type=Path, help='write the measured rows and totals (keeps `deltas`)')
    a = ap.parse_args()
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    rules = json.loads(RULES.read_text())['rows']
    backends = a.backends.split(',')
    manifest = list(csv.DictReader(MANIFEST.open(), delimiter='\t'))
    in_scope = {r['cap_id']: r for r in manifest if r['in_scope'] == 'yes'}
    unknown = sorted(set(rules) - set(in_scope))
    if unknown:
        sys.exit(f'rows.json names rows not in scope in the manifest: {unknown}')

    arch = platform_arch(a.outcomes)
    platforms = json.loads(RULES.read_text()).get('platforms', {})
    if arch not in platforms:
        sys.exit(f'no expectations recorded for architecture {arch!r} (rows.json `platforms`: {sorted(platforms)})')
    plat = platforms[arch]

    result: dict = {'backends': backends, 'arch': arch, 'rows': {}}
    mismatches = []
    for row, rule in rules.items():
        result['rows'][row] = {}
        for b in backends:
            if 'probes' in rule:
                status, cells = probe_status(row, rule, b, a.outcomes, a.expected)
            else:
                cells = []
                for cid in rule['cases']:
                    cls, bad, applied = classify_case(cid, b, rule, a.outcomes, a.expected)
                    cells.append({'case': cid, 'class': cls, 'differs': bad, 'exceptions': applied})
                status = row_status([c['class'] for c in cells])
            expect = (rule.get('expect') or {}).get('web' if b != 'vm' else 'ffi')
            expect = plat.get('rows', {}).get(row, {}).get(b, expect)
            result['rows'][row][b] = {'status': status, 'expect': expect, 'cells': cells}
            if expect and status != expect:
                mismatches.append((row, b, status, expect))

    # Totals over the manifest: re-measured rows from this run, the rest as recorded.
    totals = {}
    for b in backends:
        col = 'baseline_ffi' if b == 'vm' else 'baseline_web'
        counts: dict[str, int] = {}
        for cid, r in in_scope.items():
            st = result['rows'][cid][b]['status'] if cid in result['rows'] else r[col]
            counts[st] = counts.get(st, 0) + 1
        remeasured = {}
        for cid in result['rows']:
            st = result['rows'][cid][b]['status']
            remeasured[st] = remeasured.get(st, 0) + 1
        totals[b] = {'all_rows': counts, 're_measured': remeasured, 'n_re_measured': len(result['rows'])}
    result['totals'] = totals

    lines = ['| row | ' + ' | '.join(backends) + ' |', '|---|' + '---|' * len(backends)]
    for row in rules:
        cells = []
        for b in backends:
            r = result['rows'][row][b]
            mark = '' if not r['expect'] or r['status'] == r['expect'] else f" (recorded {r['expect']})"
            cells.append(r['status'] + mark)
        lines.append(f'| {row} | ' + ' | '.join(cells) + ' |')
    lines.append('')
    for b in backends:
        t = totals[b]
        lines.append(f"{b}: re-measured {t['n_re_measured']} rows {t['re_measured']}; "
                     f"all {len(in_scope)} in-scope rows {t['all_rows']}")
    text = '\n'.join(lines) + '\n'
    print(text)
    if a.markdown:
        a.markdown.write_text(text)
    if a.json:
        a.json.write_text(json.dumps(result, indent=1) + '\n')

    measured = {row: {b: result['rows'][row][b]['status'] for b in backends} for row in rules}
    present = {b: totals[b]['all_rows'].get('PRESENT', 0) for b in backends}
    if a.write_current:
        prev = json.loads(a.write_current.read_text()) if a.write_current.exists() else {}
        doc = {'subject': prev.get('subject', ''), 'present': present, 'totals': {b: totals[b]['all_rows'] for b in backends},
               'rows': measured, 'platforms': prev.get('platforms', {}), 'deltas': prev.get('deltas', [])}
        a.write_current.write_text(json.dumps(doc, indent=1) + '\n')
    rc = 0
    if a.assert_current:
        cur = json.loads(a.assert_current.read_text())
        cplat = cur.get('platforms', {}).get(arch)
        if cplat is None:
            sys.exit(f'{a.assert_current} records no expectations for architecture {arch!r}')
        want_rows = {row: {**cur['rows'].get(row, {}), **cplat.get('rows', {}).get(row, {})} for row in rules}
        cur = {**cur, 'present': cplat['present']}
        bad = [(row, b, measured[row][b], want_rows[row].get(b))
               for row in rules for b in backends if measured[row][b] != want_rows[row].get(b)]
        for row, b, got, want in bad:
            print(f'FAIL current row {row} on {b}: measured {got}, recorded {want} (tool/parity/baseline-current.json)')
        for b in backends:
            if present[b] != cur['present'].get(b):
                bad.append(('PRESENT', b, present[b], cur['present'].get(b)))
                print(f'FAIL current PRESENT on {b}: {present[b]}/{len(in_scope)}, recorded {cur["present"].get(b)}')
        if bad:
            rc = 1
        else:
            print(f'PASS current ({arch}): every re-measured row and the PRESENT totals match '
                  f'baseline-current.json ({", ".join(f"{b} {present[b]}/{len(in_scope)}" for b in backends)})')
    if a.assert_rows and mismatches:
        rc = 1
        for row, b, got, want in mismatches:
            print(f'FAIL row {row} on {b}: measured {got}, recorded {want}')
    if a.assert_baseline:
        frozen = json.loads(META.read_text())['baseline']['ffi']['PRESENT']
        if arch == 'arm64' and plat['present']['vm'] != frozen:
            sys.exit(f'rows.json arm64 FFI PRESENT {plat["present"]["vm"]} contradicts the manifest ({frozen})')
        for b in backends:
            want = plat['present'][b]
            got = present[b]
            label = 'FFI' if b == 'vm' else b
            if got != want:
                rc = 1
                print(f'FAIL baseline ({arch}): {label} PRESENT {got}/{len(in_scope)}, recorded {want}/{len(in_scope)}')
            else:
                print(f'PASS baseline ({arch}): {label} PRESENT {got}/{len(in_scope)}'
                      + (f' (the manifest\'s frozen baseline, measured on arm64: {frozen})'
                         if b == 'vm' and arch == 'arm64' else ''))
    if a.assert_rows and not mismatches:
        print(f'PASS rows ({arch}): every re-measured row matches its recorded status on {", ".join(backends)}')
    return rc


if __name__ == '__main__':
    sys.exit(main())
